/// The first site the fixture's libraries define — discovered, never guessed.
fn first_site(db: &cxx::UniquePtr<odb::OdbDb>) -> Option<String> {
    (0..odb::num_sites(db).ok()?)
        .filter_map(|i| odb::nth_site_name(db, i).ok())
        .find(|n| !n.is_empty())
}

#[test]
fn a_plain_site_has_no_row_pattern_and_says_so_rather_than_erroring() {
    // Absence is an answer: length 0, not a throw. The engine asks this of every site to decide
    // between the uniform and hybrid paths, so it must be cheap and total.
    let db = odb::open_db(FIXTURE).expect("read");
    let site = first_site(&db).expect("a site");
    assert!(
        !odb::site_has_row_pattern(&db, &site),
        "the fixture's sites are plain"
    );
    assert_eq!(odb::site_row_pattern_len(&db, &site).unwrap(), 0);
    assert_eq!(
        odb::site_row_pattern_len(&db, "no_such_site_xyz").unwrap(),
        0
    );

    // Indexing a pattern that is not there is an error, not an empty string that would read as
    // a real site named "".
    assert!(odb::site_row_pattern_site(&db, &site, 0).is_err());
    assert!(odb::site_row_pattern_orient(&db, &site, 0).is_err());
}

#[test]
fn rows_are_cut_around_a_blockage_and_an_unknown_one_is_refused() {
    // Row cutting is odb's own algorithm; what is checked here is that the bridge reaches it and
    // that the blockage list is resolved by name rather than silently ignored.
    let db = odb::open_db(FIXTURE).expect("read");
    let site = first_site(&db).expect("site");
    let (w, h) = (
        odb::site_get_width(&db, &site),
        odb::site_get_height(&db, &site),
    );

    odb::clear_rows(&db).unwrap();
    odb::block_set_die_area(&db, 0, 0, w * 400, h * 8).unwrap();
    for r in 0..4 {
        odb::row_create(
            &db,
            &format!("R{r}"),
            &site,
            0,
            r * h,
            "R0",
            "HORIZONTAL",
            300,
            w,
        )
        .unwrap();
    }
    let before = odb::num_rows(&db).unwrap();

    // No blockages: nothing to cut around, so the row count cannot fall.
    odb::block_cut_rows(&db, 0, &[], 0, 0).unwrap();
    assert_eq!(odb::num_rows(&db).unwrap(), before, "no blockage, no cut");

    // A name the block does not define is an error -- cutting around nothing would look like
    // success and leave rows crossing a macro.
    assert!(odb::block_cut_rows(&db, 0, &["no_such_inst_xyz".to_string()], 0, 0).is_err());

    // A real instance cuts the rows it overlaps into pieces, so the count RISES.
    let inst = odb::nth_inst_name(&db, 0);
    assert!(!inst.is_empty(), "the fixture has instances");
    odb::block_cut_rows(&db, 0, std::slice::from_ref(&inst), 0, 0).unwrap();
    assert!(
        odb::num_rows(&db).unwrap() >= before,
        "cutting splits rows in two around the macro, it never loses them silently"
    );
}

